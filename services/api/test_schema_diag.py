def test_the_hot_path_screen_never_rejects_what_the_exact_reader_accepts():
    """The contract between the two readers is ONE-DIRECTIONAL, and that is deliberate.

    `scan_unterminated_string` is the hot-path screen (quote parity, then a confirm);
    `_text_ends_in_string` is the exact comment-aware reader. They are NOT required to agree, because
    the two ways of disagreeing are not equally harmful:

    - screen says **unterminated** while the exact reader says fine -> a valid model is REFUSED. This
      must never happen, and is what this test asserts.
    - screen says **fine** while the exact reader says unterminated -> the parser crashes on a file it
      was already crashing on before the screen existed. No regression, and it is the direction parity
      can fail in when a `/* … */` comment holds a stray apostrophe.

    Asserting plain equality here would be asserting the wrong contract, and would have to be weakened
    the first time a commented file turned up — a test that gets relaxed under pressure was measuring
    the wrong thing.
    """
    import shutil
    import tempfile

    cases = [
        "no quotes at all",
        "'closed'",
        "'unclosed",
        "'it''s closed'",
        "'it''s unclosed",
        "'a'" * 700,                          # crosses the chunk boundary many times
        "'" + "x" * (SD._CHUNK - 1) + "'",    # a closing quote as the first byte of chunk 2
        "'" + "x" * (SD._CHUNK - 1),          # opens in chunk 1, never closes
        "'a''" + "b" * SD._CHUNK + "'",       # an escaped quote landing on the boundary
        "/* it''s fine */'closed'",           # apostrophe escaped inside a comment
        "/* it's odd */'closed'",             # a LONE apostrophe in a comment: parity says odd
        "/* it's odd */'unclosed",            # the documented false-negative case
    ]
    d = tempfile.mkdtemp()
    tolerated = 0
    try:
        for i, text in enumerate(cases):
            p = os.path.join(d, f"c{i}.ifc")
            with open(p, "w", encoding="utf-8") as fh:
                fh.write(text)
            screen = SD.scan_unterminated_string(p)
            exact = SD._text_ends_in_string(text)
            assert not (screen and not exact), (
                f"case {i} would REFUSE A VALID FILE: screen={screen} exact={exact} for {text[:50]!r}")
            if exact and not screen:
                tolerated += 1
    finally:
        # rmtree, not rmdir: on Windows a just-closed handle can still be held briefly, and a cleanup
        # failure must not be reported as a failure of the thing under test.
        shutil.rmtree(d, ignore_errors=True)
    # The tolerated direction must be REACHED by this test, not merely allowed by it — otherwise the
    # assertion above is the only live one and the asymmetry is untested prose.
    assert tolerated == 1, f"expected exactly the one documented false negative, got {tolerated}"


def test_a_comment_with_an_apostrophe_is_not_refused():
    """The specific false positive the parity filter is designed to avoid.

    A lone `'` inside `/* … */` shifts quote parity, so the cheap filter calls the file suspicious. If
    odd parity decided on its own, this valid model would be refused. It escalates to the comment-aware
    confirm instead, which is the whole reason the filter is only trusted in one direction.
    """
    import shutil
    import tempfile

    d = tempfile.mkdtemp()
    try:
        p = os.path.join(d, "commented.ifc")
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(MINIMAL.replace("DATA;", "DATA;\n/* exported by Bob's tool */"))
        assert SD.scan_unterminated_string(p) is False
    finally:
        shutil.rmtree(d, ignore_errors=True)


def test_the_engine_is_REACHABLE_over_http():
    """An engine with no route is indistinguishable from a working feature, from the outside.

    Seven of eleven things built across v0.3.701-710 shipped with no route. `test_reachable.py` is the
    gate for that, but it walks the import graph of **`aec_api`** and this engine lives in `aec_data`,
    so it is not covered there — and the route imports it lazily inside the handler, which a
    direct-reference check would not see either. So it is asserted here, over HTTP, with a started app.

    Both halves matter and they caught different things. Presence in the OpenAPI schema proved the route
    was *defined*; the request proved it was *callable*, and the first version was in the schema and
    raised `NameError` on every call — `source_ifc_path` is imported into that module as `_source_ifc`.
    A schema-only assertion would have shipped it.

    The status is compared against the SIBLING endpoints rather than pinned to a literal: what must be
    true is that this route is guarded exactly like the others, and a hard-coded 404 would keep passing
    if the whole family started returning 500.
    """
    from fastapi.testclient import TestClient

    from aec_api.main import app

    path = "/projects/{pid}/models/schema-diag"
    with TestClient(app) as c:
        assert path in app.openapi()["paths"], "route not served — nothing can call the engine"
        mine = c.get("/projects/no-such-project/models/schema-diag").status_code
        siblings = [c.get(f"/projects/no-such-project/models/{p}").status_code
                    for p in ("norm-valid", "qa")]
        assert mine < 500, f"schema-diag returned {mine} — the handler raised"
        assert all(mine == s for s in siblings), (
            f"schema-diag={mine} but siblings={siblings}; the guard differs from the family it joined")


